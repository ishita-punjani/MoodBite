"""Build supabase/seed.sql from the CSVs in data/.

The seed upserts moods, restaurants, dishes and dish_moods (zones are created
by migration 20261020000200_zones.sql). Embeddings are NOT part of the seed;
scripts/embed.py fills them afterwards.

Run scripts/check_data.py first; this script refuses to build if it fails.

Usage:  python scripts/build_seed.py
"""

from __future__ import annotations

import csv
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data"
OUT = ROOT / "supabase" / "seed.sql"


def q(value: str) -> str:
    return "'" + value.replace("'", "''") + "'"


def text_array(pipe_separated: str) -> str:
    items = [s for s in pipe_separated.split("|") if s]
    return "array[" + ", ".join(q(s) for s in items) + "]::text[]" if items else "'{}'::text[]"


def read(name: str) -> list[dict]:
    with (DATA / name).open(encoding="utf-8", newline="") as f:
        return list(csv.DictReader(f))


def values_block(rows: list[str]) -> str:
    return ",\n".join(f"  {r}" for r in rows)


def main() -> int:
    check = subprocess.run([sys.executable, str(ROOT / "scripts" / "check_data.py")], capture_output=True, text=True)
    if check.returncode != 0:
        print(check.stdout)
        print("check_data.py failed; fix the data before building the seed.")
        return 1

    moods = read("moods.csv")
    restaurants = read("restaurants.csv")
    dishes = read("dishes.csv")
    dish_moods = read("dish_moods.csv")

    parts = [
        "-- GENERATED by scripts/build_seed.py from data/*.csv. Do not edit by hand.",
        "-- Demo data: real Mumbai restaurant names with ILLUSTRATIVE menus and prices.",
        "-- Safe to re-run: rows are upserted by id.",
        "",
        "begin;",
        "",
        "insert into public.moods (id, label, emoji, description) values",
        values_block([f"({q(m['id'])}, {q(m['label'])}, {q(m['emoji'])}, {q(m['description'])})" for m in moods]),
        "on conflict (id) do update set label = excluded.label, emoji = excluded.emoji,",
        "  description = excluded.description;",
        "",
        "insert into public.restaurants (id, name, area, address, lat, lng, cuisine, price_level, is_open, coords_verified) values",
        values_block([
            f"({q(r['id'])}, {q(r['name'])}, {q(r['area'])}, {q(r['address'])}, {r['lat']}, {r['lng']}, "
            f"{text_array(r['cuisine'])}, {r['price_level']}, {r['is_open']}, {r['coords_verified']})"
            for r in restaurants
        ]),
        "on conflict (id) do update set name = excluded.name, area = excluded.area, address = excluded.address,",
        "  lat = excluded.lat, lng = excluded.lng, cuisine = excluded.cuisine, price_level = excluded.price_level,",
        "  is_open = excluded.is_open, coords_verified = excluded.coords_verified;",
        "",
        "insert into public.dishes (id, restaurant_id, name, description, price_inr, is_veg, category) values",
        values_block([
            f"({q(d['id'])}, {q(d['restaurant_id'])}, {q(d['name'])}, {q(d['description'])}, "
            f"{d['price_inr']}, {d['is_veg']}, {q(d['category'])})"
            for d in dishes
        ]),
        "on conflict (id) do update set restaurant_id = excluded.restaurant_id, name = excluded.name,",
        "  description = excluded.description, price_inr = excluded.price_inr, is_veg = excluded.is_veg,",
        "  category = excluded.category;",
        "",
        "-- Mood tags are replaced wholesale so removed tags do not linger.",
        "delete from public.dish_moods;",
        "insert into public.dish_moods (dish_id, mood_id, weight) values",
        values_block([f"({q(dm['dish_id'])}, {q(dm['mood_id'])}, {dm['weight']})" for dm in dish_moods]) + ";",
        "",
        "commit;",
        "",
    ]
    OUT.write_text("\n".join(parts), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}: {len(moods)} moods, {len(restaurants)} restaurants, "
          f"{len(dishes)} dishes, {len(dish_moods)} dish_moods")
    return 0


if __name__ == "__main__":
    sys.exit(main())
