"""Look up restaurant coordinates on OpenStreetMap Nominatim.

Follows the Nominatim usage policy: identifying User-Agent, at most one
request per second, results cached so a re-run does not repeat requests.

A result is accepted (coords_verified=true) only if it is a named place
(amenity/shop/tourism), its name matches the restaurant name, and it lies
within ACCEPT_RADIUS_KM of the restaurant's area centre. Otherwise the area
centroid is kept and coords_verified=false, for the user to spot-check.

Writes:
  data/restaurants.csv      lat, lng, coords_verified updated in place
  data/geocode_report.csv   what was matched for every restaurant
  data/geocode_cache.json   raw responses (safe to delete to force a re-run)
  data/REVIEW.md            restaurants to spot-check on a map

Map data (c) OpenStreetMap contributors, ODbL.

Usage:  python scripts/geocode.py
"""

from __future__ import annotations

import csv
import json
import math
import re
import sys
import time
import urllib.error
import urllib.parse
import urllib.request
from pathlib import Path

DATA = Path(__file__).resolve().parent.parent / "data"
CACHE = DATA / "geocode_cache.json"
ENDPOINT = "https://nominatim.openstreetmap.org/search"
USER_AGENT = "MoodBite-academic-demo/0.1 (student mini project; one-off geocoding of 50 restaurants)"
MIN_INTERVAL_S = 1.1
ACCEPT_RADIUS_KM = 3.0
ACCEPT_CLASSES = {"amenity", "shop", "tourism"}
# left, top, right, bottom
MUMBAI_VIEWBOX = "72.75,19.32,73.00,18.85"
STOPWORDS = {"the", "and", "co", "cafe", "restaurant", "hotel", "centre", "center", "of", "at"}

_last_request = 0.0


def haversine_km(lat1: float, lng1: float, lat2: float, lng2: float) -> float:
    r = 6371.0
    p1, p2 = math.radians(lat1), math.radians(lat2)
    dp, dl = p2 - p1, math.radians(lng2 - lng1)
    a = math.sin(dp / 2) ** 2 + math.cos(p1) * math.cos(p2) * math.sin(dl / 2) ** 2
    return 2 * r * math.asin(math.sqrt(a))


def tokens(text: str) -> set[str]:
    words = re.findall(r"[a-z0-9]+", text.lower().replace("'s", ""))
    return {w for w in words if w not in STOPWORDS}


def name_matches(restaurant: str, osm_name: str) -> bool:
    want, got = tokens(restaurant), tokens(osm_name)
    if not want or not got:
        return False
    return len(want & got) / len(want) >= 0.6


def search(query: str, cache: dict) -> list[dict]:
    global _last_request
    if query in cache:
        return cache[query]
    wait = MIN_INTERVAL_S - (time.monotonic() - _last_request)
    if wait > 0:
        time.sleep(wait)
    params = urllib.parse.urlencode({
        "q": query,
        "format": "jsonv2",
        "limit": 5,
        "countrycodes": "in",
        "viewbox": MUMBAI_VIEWBOX,
        "bounded": 1,
    })
    request = urllib.request.Request(f"{ENDPOINT}?{params}", headers={"User-Agent": USER_AGENT})
    _last_request = time.monotonic()
    with urllib.request.urlopen(request, timeout=20) as response:
        results = json.loads(response.read().decode("utf-8"))
    cache[query] = results
    CACHE.write_text(json.dumps(cache, indent=1, ensure_ascii=False), encoding="utf-8")
    return results


def best_match(name: str, centre: tuple[float, float], results: list[dict]) -> tuple[dict, float] | None:
    for result in results:
        if result.get("category", result.get("class")) not in ACCEPT_CLASSES:
            continue
        osm_name = result.get("name") or result.get("display_name", "").split(",")[0]
        if not name_matches(name, osm_name):
            continue
        km = haversine_km(centre[0], centre[1], float(result["lat"]), float(result["lon"]))
        if km <= ACCEPT_RADIUS_KM:
            return result, km
    return None


def closest_candidate(centre: tuple[float, float], results: list[dict]) -> str:
    """Nearest named place among the results, for the human reviewer. Never auto-accepted."""
    best = None
    for result in results:
        if result.get("category", result.get("class")) not in ACCEPT_CLASSES:
            continue
        km = haversine_km(centre[0], centre[1], float(result["lat"]), float(result["lon"]))
        if best is None or km < best[0]:
            best = (km, result)
    if best is None:
        return ""
    km, result = best
    name = result.get("name") or result.get("display_name", "").split(",")[0]
    return (f"'{name}' ({result.get('type')}) {km:.1f} km from area centre: "
            f"https://www.openstreetmap.org/{result['osm_type']}/{result['osm_id']}")


def write_review(restaurants: list[dict], report: list[list]) -> None:
    by_id = {row[0]: row for row in report}
    lines = [
        "# Restaurant coordinates to review",
        "",
        "Generated by `scripts/geocode.py`. Map data (c) OpenStreetMap contributors.",
        "",
        "Restaurants with `coords_verified=false` currently sit on their AREA CENTROID (not their real location).",
        "For each one: open the map link, find the restaurant, and either paste the correct lat/lng into",
        "`data/restaurants.csv` (and set `coords_verified` to `true`) or leave it on the centroid.",
        "\"Closest OSM candidate\" is only a hint: it was NOT accepted automatically because its name or",
        "distance did not pass the checks.",
        "",
        "| ID | Restaurant | Area | Centroid used (lat, lng) | Map at centroid | Closest OSM candidate |",
        "|---|---|---|---|---|---|",
    ]
    for r in restaurants:
        if r["coords_verified"] == "true":
            continue
        lat, lng = r["lat"], r["lng"]
        link = f"https://www.openstreetmap.org/?mlat={lat}&mlon={lng}#map=15/{lat}/{lng}"
        lines.append(f"| {r['id']} | {r['name']} | {r['area']} | {lat}, {lng} | [map]({link}) | {by_id[r['id']][8] or '-'} |")
    lines += [
        "",
        "## Matched automatically (spot-check a few)",
        "",
        "| ID | Restaurant | Area | OSM match | km from area centre |",
        "|---|---|---|---|---|",
    ]
    for r in restaurants:
        if r["coords_verified"] == "true":
            row = by_id[r["id"]]
            lines.append(f"| {r['id']} | {r['name']} | {r['area']} | [{row[5].split(',')[0]}]({row[7]}) | {row[6]} |")
    (DATA / "REVIEW.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> int:
    zones = {z["name"]: (float(z["lat"]), float(z["lng"])) for z in csv.DictReader((DATA / "zones.csv").open(encoding="utf-8"))}
    with (DATA / "restaurants.csv").open(encoding="utf-8", newline="") as f:
        reader = csv.DictReader(f)
        fields = reader.fieldnames
        restaurants = list(reader)
    cache = json.loads(CACHE.read_text(encoding="utf-8")) if CACHE.exists() else {}

    report = []
    for r in restaurants:
        centre = zones[r["area"]]
        queries = [f"{r['name']}, {r['area']}, Mumbai", f"{r['name']}, Mumbai"]
        match, used, note, candidate = None, "", "", ""
        for query in queries:
            try:
                results = search(query, cache)
            except (urllib.error.URLError, TimeoutError, json.JSONDecodeError) as e:
                note = f"request failed: {e}"
                break
            match = best_match(r["name"], centre, results)
            if match:
                used = query
                break
            note = f"{len(results)} results, none matched"
            candidate = candidate or closest_candidate(centre, results)

        if match:
            result, km = match
            r["lat"], r["lng"] = f"{float(result['lat']):.6f}", f"{float(result['lon']):.6f}"
            r["coords_verified"] = "true"
            report.append([r["id"], r["name"], r["area"], "true", used, result.get("display_name", ""),
                           f"{km:.2f}", f"https://www.openstreetmap.org/{result['osm_type']}/{result['osm_id']}", "", ""])
        else:
            r["lat"], r["lng"] = f"{centre[0]:.6f}", f"{centre[1]:.6f}"
            r["coords_verified"] = "false"
            report.append([r["id"], r["name"], r["area"], "false", "", "", "", "", candidate,
                           f"area centroid used; {note}"])
        print(f"{r['id']} {r['name']:<34} verified={r['coords_verified']}")

    with (DATA / "restaurants.csv").open("w", encoding="utf-8", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=fields)
        writer.writeheader()
        writer.writerows(restaurants)
    with (DATA / "geocode_report.csv").open("w", encoding="utf-8", newline="") as f:
        writer = csv.writer(f)
        writer.writerow(["id", "name", "area", "coords_verified", "query", "osm_display_name",
                         "km_from_area_centre", "osm_link", "closest_candidate", "note"])
        writer.writerows(report)
    write_review(restaurants, report)

    verified = sum(1 for r in restaurants if r["coords_verified"] == "true")
    print(f"\nverified {verified}/{len(restaurants)}; the rest use the area centroid (coords_verified=false)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
